#!/usr/bin/env ts-node
/**
 * Generates src/fieldmaps/f1099b.layout.ts: for each tax year, every Form 1099-B
 * field (all four copies) → a semantic key. Within a copy, IRS numbers the boxes
 * the same way in every year (f?_16 = box 1a, c?_4[0..2] = box 2 …); only the
 * container paths differ, which is why the full names are generated rather than
 * written by hand. Re-run after replacing a year's f1099b.pdf and its template:
 *
 *   npx ts-node scripts/gen-1099b-map.ts
 */
import fs from "fs";
import path from "path";

const TEXT: Record<number, string> = {
  1: "payer", 2: "payerTin", 3: "recipientTin", 4: "recipientName", 5: "street", 6: "city",
  7: "account", 8: "cusip", 9: "state1", 10: "state2", 11: "stateId1", 12: "stateId2",
  13: "stateTax1", 14: "stateTax2", 15: "form8949Box", 16: "box1a", 17: "box1b", 18: "box1c",
  19: "box1d", 20: "box1e", 21: "box1f", 22: "box1g", 23: "box4", 24: "box8", 25: "box9",
  26: "box10", 27: "box11", 28: "box13",
};
const CHECK: Record<string, string> = {
  "1": "corrected", "2": "secondTinNotice", "3": "fatca", "4.0": "box2.short", "4.1": "box2.long",
  "4.2": "box2.ordinary", "5.0": "box3.collectibles", "5.1": "box3.qof", "6": "box5.noncovered",
  "7.0": "box6.gross", "7.1": "box6.net", "8": "box7.lossNotAllowed", "9": "box12.basisReported",
};

const out: Record<number, Record<string, string>> = {};
for (const year of [2023, 2024, 2025]) {
  const t = JSON.parse(fs.readFileSync(path.join(`templates_${year}`, "f1099b.json"), "utf8"));
  out[year] = {};
  for (const f of t.fields as Array<{ pdfFieldName: string }>) {
    const copy = /\.(Copy\w+?)\[0\]\./.exec(f.pdfFieldName)?.[1];
    const m = /\.([fc])\d+_(\d+)\[(\d+)\]$/.exec(f.pdfFieldName);
    if (!copy || !m) throw new Error(`unrecognised 1099-B field ${f.pdfFieldName}`);
    const [, kind, n, idx] = m;
    const key = kind === "f" ? TEXT[Number(n)] : (CHECK[`${n}.${idx}`] ?? (idx === "0" ? CHECK[n] : undefined)) ?? (n === "1" ? "corrected" : undefined);
    if (!key) throw new Error(`no key for ${f.pdfFieldName}`);
    out[year][f.pdfFieldName] = `${copy}.${key}`;
  }
}
const body = `// Generated by scripts/gen-1099b-map.ts — do not edit by hand.
/** Tax year → Form 1099-B field name → "<copy>.<semantic key>". */
export const F1099B_LAYOUT: Record<number, Record<string, string>> = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync("src/fieldmaps/f1099b.layout.ts", body);
console.log(Object.entries(out).map(([y, m]) => `${y}: ${Object.keys(m).length} fields`).join(", "));
