#!/usr/bin/env ts-node
/**
 * Generates src/fieldmaps/<formId>.index.ts: for each tax year, the form's short
 * field name ("f1_20", "c2_3[1]" — unpadded number, plus the index when it isn't
 * [0]) → full pdfFieldName. For forms whose numbering stays the same across years
 * while the containers / zero-padding change, a map written for one year can then
 * be translated to the others by short name. Re-run after replacing a PDF and
 * rebuilding its template:
 *
 *   npx ts-node scripts/gen-field-index.ts f8582
 */
import fs from "fs";
import path from "path";

const shortName = (full: string) => {
  const m = /\.([fc]\d+_)0*(\d+)\[(\d+)\]$/.exec(full);
  if (!m) throw new Error(`unrecognised field name ${full}`);
  return `${m[1]}${m[2]}${m[3] === "0" ? "" : `[${m[3]}]`}`;
};

for (const formId of process.argv.slice(2)) {
  const out: Record<number, Record<string, string>> = {};
  for (const year of [2023, 2024, 2025]) {
    const file = path.join(`templates_${year}`, `${formId}.json`);
    if (!fs.existsSync(file)) continue;
    out[year] = {};
    for (const f of JSON.parse(fs.readFileSync(file, "utf8")).fields as Array<{ pdfFieldName: string }>) {
      const k = shortName(f.pdfFieldName);
      if (out[year][k]) throw new Error(`${formId} ${year}: short name ${k} is not unique`);
      out[year][k] = f.pdfFieldName;
    }
  }
  const constName = `${formId.toUpperCase()}_INDEX`;
  fs.writeFileSync(path.join("src/fieldmaps", `${formId}.index.ts`),
    `// Generated by scripts/gen-field-index.ts — do not edit by hand.\n` +
    `/** Tax year → short field name → full pdfFieldName. */\n` +
    `export const ${constName}: Record<number, Record<string, string>> = ${JSON.stringify(out, null, 1)};\n` +
    `export const shortFieldName = (full: string): string => {\n` +
    `  const m = /\\.([fc]\\d+_)0*(\\d+)\\[(\\d+)\\]$/.exec(full);\n` +
    `  if (!m) throw new Error(\`unrecognised field name \${full}\`);\n` +
    `  return \`\${m[1]}\${m[2]}\${m[3] === "0" ? "" : \`[\${m[3]}]\`}\`;\n};\n`);
  console.log(`${formId}: ${Object.entries(out).map(([y, m]) => `${y} ${Object.keys(m).length}`).join(", ")}`);
}
