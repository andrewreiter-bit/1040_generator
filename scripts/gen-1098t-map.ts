#!/usr/bin/env ts-node
/**
 * Generates src/fieldmaps/f1098t.layout.ts: for each tax year, every Form 1098-T field (all
 * copies: A, B, and C in 2023) → "<copy>.<semantic key>". Within a copy the boxes are
 * numbered the same way in 2023–2025 (f?_8 = box 1, c?_4 = box 8 …); only the containers
 * differ. Re-run after replacing a year's f1098t.pdf and its template:
 *
 *   npx ts-node scripts/gen-1098t-map.ts
 */
import fs from "fs";
import path from "path";

const TEXT: Record<number, string> = {
  1: "filer", 2: "filerEin", 3: "studentTin", 4: "studentName", 5: "street", 6: "city", 7: "account",
  8: "box1", 9: "box4", 10: "box5", 11: "box6", 12: "box10",
};
const CHECK: Record<number, string> = { 3: "box7", 4: "box8", 5: "box9" };

const out: Record<number, Record<string, string>> = {};
for (const year of [2023, 2024, 2025]) {
  const t = JSON.parse(fs.readFileSync(path.join(`templates_${year}`, "f1098t.json"), "utf8"));
  out[year] = {};
  for (const f of t.fields as Array<{ pdfFieldName: string }>) {
    const copy = /\.(Copy\w+?)\[0\]/.exec(f.pdfFieldName)?.[1];
    const m = /\.([fc])\d+_(\d+)\[(\d+)\]$/.exec(f.pdfFieldName);
    if (!copy || !m) throw new Error(`unrecognised 1098-T field ${f.pdfFieldName}`);
    const [, kind, n, idx] = m;
    // c?_1 / c?_2 are the VOID / CORRECTED boxes (Copy A has both, the others CORRECTED only).
    const key = kind === "f" ? TEXT[Number(n)] : Number(n) <= 2 ? `corrected${n}.${idx}` : CHECK[Number(n)];
    if (!key) throw new Error(`no key for ${f.pdfFieldName}`);
    out[year][f.pdfFieldName] = `${copy}.${key}`;
  }
}
const body = `// Generated by scripts/gen-1098t-map.ts — do not edit by hand.
/** Tax year → Form 1098-T field name → "<copy>.<semantic key>". */
export const F1098T_LAYOUT: Record<number, Record<string, string>> = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync("src/fieldmaps/f1098t.layout.ts", body);
console.log(Object.entries(out).map(([y, m]) => `${y}: ${Object.keys(m).length} fields`).join(", "));
