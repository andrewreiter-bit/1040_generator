#!/usr/bin/env ts-node
/**
 * Generates src/fieldmaps/f1099r.layout.ts: for each tax year, every Form 1099-R
 * field (all copies: A, 1, B, C, 2, and D in 2023) → "<copy>.<semantic key>".
 * Within a copy the boxes are numbered the same way in 2023–2025 (f?_08 = box 1,
 * c?_4 = IRA/SEP/SIMPLE …); only the copy containers differ. Re-run after
 * replacing a year's f1099r.pdf and its template:
 *
 *   npx ts-node scripts/gen-1099r-map.ts
 */
import fs from "fs";
import path from "path";

const TEXT: Record<number, string> = {
  1: "payer", 2: "payerTin", 3: "recipientTin", 4: "recipientName", 5: "street", 6: "city", 7: "account",
  8: "box1", 9: "box2a", 10: "box3", 11: "box4", 12: "box5", 13: "box6", 14: "box7", 15: "box8", 16: "box8pct",
  17: "box9a", 18: "box9b", 19: "box10", 20: "box11", 21: "box13", 22: "box14a", 23: "box14b", 24: "box15a",
  25: "box15b", 26: "box16a", 27: "box16b", 28: "box17a", 29: "box17b", 30: "box18a", 31: "box18b", 32: "box19a", 33: "box19b",
};
const CHECK: Record<string, string> = {
  "1.0": "void", "1.1": "corrected", "2.0": "box2b.notDetermined", "3.0": "box2b.total", "4.0": "box7.iraSepSimple", "5.0": "box12.fatca",
};

const out: Record<number, Record<string, string>> = {};
for (const year of [2023, 2024, 2025]) {
  const t = JSON.parse(fs.readFileSync(path.join(`templates_${year}`, "f1099r.json"), "utf8"));
  out[year] = {};
  for (const f of t.fields as Array<{ pdfFieldName: string }>) {
    const copy = /\.(Copy\w+?)\[0\]/.exec(f.pdfFieldName)?.[1];
    const m = /\.([fc])\d+_(\d+)\[(\d+)\]$/.exec(f.pdfFieldName);
    if (!copy || !m) throw new Error(`unrecognised 1099-R field ${f.pdfFieldName}`);
    const [, kind, n, idx] = m;
    // Copies A and 1 have VOID + CORRECTED (c?_1[0], [1]); the others only CORRECTED (c?_1[0]).
    let key = kind === "f" ? TEXT[Number(n)] : CHECK[`${Number(n)}.${idx}`];
    if (kind === "c" && Number(n) === 1 && !/^Copy(A|1)$/.test(copy)) key = "corrected";
    if (!key) throw new Error(`no key for ${f.pdfFieldName}`);
    out[year][f.pdfFieldName] = `${copy}.${key}`;
  }
}
const body = `// Generated by scripts/gen-1099r-map.ts — do not edit by hand.
/** Tax year → Form 1099-R field name → "<copy>.<semantic key>". */
export const F1099R_LAYOUT: Record<number, Record<string, string>> = ${JSON.stringify(out, null, 1)};
`;
fs.writeFileSync("src/fieldmaps/f1099r.layout.ts", body);
console.log(Object.entries(out).map(([y, m]) => `${y}: ${Object.keys(m).length} fields`).join(", "));
